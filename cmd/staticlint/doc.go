// Package main реализует multichecker для статического анализа кода.
//
// Multichecker объединяет несколько групп анализаторов:
//
// 1. Стандартные анализаторы пакета golang.org/x/tools/go/analysis/passes:
//
//   - asmdecl - проверка объявлений ассемблерных функций
//
//   - assign - обнаружение бесполезных присваиваний
//
//   - atomic - проверка корректности использования atomic-операций
//
//   - bools - поиск подозрительных логических операций
//
//   - buildtag - проверка тегов сборки
//
//   - composite - проверка неинициализированных составных литералов
//
//   - copylock - обнаружение копирования блокировок (mutex)
//
//   - httpresponse - проверка использования HTTP-ответов
//
//   - loopclosure - поиск захвата переменных цикла в замыканиях
//
//   - lostcancel - поиск утечки контекста (невызов cancel)
//
//   - nilfunc - проверка вызова nil-функций
//
//   - printf - проверка форматной строки в printf-подобных функциях
//
//   - shift - проверка подозрительных битовых сдвигов
//
//   - stdmethods - проверка сигнатур стандартных методов
//
//   - structtag - проверка тегов структур
//
//   - tests - проверка тестов и бенчмарков
//
//   - unmarshal - проверка передачи не-указателей в Unmarshal
//
//   - unreachable - поиск недостижимого кода
//
//   - unsafeptr - проверка unsafe.Pointer
//
//   - unusedresult - поиск неиспользуемых возвращаемых значений
//
//     2. Анализаторы класса SA пакета staticcheck.io (все проверки):
//     Содержит около 80 анализаторов для поиска серьёзных ошибок и багов,
//     включая проверки конкурентности, утечек, неэффективного кода.
//
// 3. Анализаторы других классов staticcheck.io:
//   - ST (style) - стилистические замечания
//   - QF (quickfix) - предложения по быстрому исправлению кода
//
// 4. Публичные анализаторы:
//   - nilerr (github.com/gostaticanalysis/nilerr) - поиск ошибочного
//     возврата nil вместо ошибки (return nil, err)
//   - tenv (github.com/sivchari/tenv) - проверка использования
//     os.Setenv в тестах, требует замены на t.Setenv
//
// 5. Кастомный анализатор:
//   - noosexit - запрещает прямой вызов os.Exit в функции main пакета main.
//     Игнорирует сгенерированные файлы и кэш сборки Go.
//
// Механизм запуска multichecker:
//
// Локальный запуск без сборки:
//
//	go run ./cmd/staticlint ./...
//
// Локальный запуск конкретного пакета:
//
//	go run ./cmd/staticlint ./internal/...
//
// Сборка бинарного файла:
//
//	go build -o staticlint ./cmd/staticlint
//
// Запуск собранного бинарника:
//
//	./staticlint ./...
//
// Запуск с автоматическим исправлением (для QF-анализаторов):
//
//	./staticlint -fix ./...
//
// Multichecker использует стандартный механизм analysis.Multichecker,
// который запускает каждый анализатор независимо и выводит результаты
// в едином формате с указанием позиции в коде и описанием проблемы.
